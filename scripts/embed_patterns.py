#!/usr/bin/env python3
"""Compile the source MIDI files into a C header.

The plugin cannot read files at runtime: every MIDI FX entry point runs on
the SPI audio callback, where file I/O is forbidden (src/host/plugin_api_v1.h).
So the bytes are embedded here, at build time, and parsed in memory.

    embed_patterns.py <patterns_dir> <out_header> [<module.json in> <module.json out>]

Reads <patterns_dir>/patterns.txt (one "file.mid [start_step]" per line), or
every *.mid in the directory, sorted, when there is no manifest.  With the
optional module.json pair, it also rewrites the `source` enum options to
match the number of files, so the device UI never offers a source that does
not exist.
"""
import json
import pathlib
import sys

MAX_SOURCES = 16


def read_manifest(pdir):
    manifest = pdir / "patterns.txt"
    if not manifest.exists():
        return [(p.name, 0) for p in sorted(pdir.glob("*.mid"))]
    entries = []
    for lineno, raw in enumerate(manifest.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) > 2:
            sys.exit(f"{manifest}:{lineno}: expected 'file.mid [start_step]'")
        start = int(parts[1]) if len(parts) == 2 else 0
        if start < 0:
            sys.exit(f"{manifest}:{lineno}: start_step must be >= 0")
        entries.append((parts[0], start))
    return entries


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) not in (3, 5):
        sys.exit(__doc__)
    pdir = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2])
    entries = read_manifest(pdir)
    if not entries:
        sys.exit(f"no patterns found in {pdir}")
    if len(entries) > MAX_SOURCES:
        sys.exit(f"{len(entries)} patterns listed; the maximum is {MAX_SOURCES}")

    lines = [
        "/* GENERATED by scripts/embed_patterns.py from patterns/ -- do not edit. */",
        "#ifndef PG_PATTERNS_DATA_H",
        "#define PG_PATTERNS_DATA_H",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    const char    *name;",
        "    const uint8_t *data;",
        "    unsigned       len;",
        "    int            start_step;",
        "} pg_embedded_pattern_t;",
        "",
    ]
    for i, (name, _) in enumerate(entries):
        path = pdir / name
        if not path.is_file():
            sys.exit(f"pattern file not found: {path}")
        data = path.read_bytes()
        if data[:4] != b"MThd":
            sys.exit(f"not a Standard MIDI File: {path}")
        if len(name.encode()) >= 32:
            sys.exit(f"file name too long (max 31 bytes): {name}")
        body = ",".join(f"0x{b:02x}" for b in data)
        lines.append(f"static const uint8_t pg_embedded_{i}[{len(data)}] = {{{body}}};")
    lines += ["", "static const pg_embedded_pattern_t PG_EMBEDDED_PATTERNS[] = {"]
    for i, (name, start) in enumerate(entries):
        lines.append(f"    {{ {c_string(name)}, pg_embedded_{i}, sizeof(pg_embedded_{i}), {start} }},")
    lines += ["};", f"#define PG_EMBEDDED_COUNT {len(entries)}", "", "#endif", ""]

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"embedded {len(entries)} pattern(s): " + ", ".join(n for n, _ in entries))

    if len(sys.argv) == 5:
        src, dst = pathlib.Path(sys.argv[3]), pathlib.Path(sys.argv[4])
        mj = json.loads(src.read_text(encoding="utf-8"))
        options = ["random"] + [str(i + 1) for i in range(len(entries))]

        def patch(params):
            for p in params:
                if isinstance(p, dict) and p.get("key") == "source":
                    p["options"] = options

        caps = mj.get("capabilities", {})
        patch(caps.get("chain_params", []))
        for level in caps.get("ui_hierarchy", {}).get("levels", {}).values():
            patch(level.get("params", []))
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(json.dumps(mj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
